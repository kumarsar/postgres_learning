-- SCD3 dimension (item_id auto-generated)
CREATE TABLE dim_product (
    item_id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          int  NOT NULL UNIQUE,    -- business key, needed for matching
    product_name        text NOT NULL,
    current_category    text NOT NULL,
    previous_category   text,
    category_changed_on date
);

-- Staging: one row per product with its target category
CREATE TABLE stg_product (
    product_id   int,
    product_name text,
    category     text
);

