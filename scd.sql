create or replace procedure load_dim_product_scd3()
language plpgsql as 

$$
	BEGIN
		-- 1) Changed rows: shift current -> previous, then overwrite current
		update dim_product d

		set previous_category = d.current_category,
			current_category = s.category,
			category_changed_on = current_date

		from stg_product s

		where d.product_id = s.product_id
			AND d.current_category IS DISTINCT FROM s.category;

		-- 2) Brand-new rows
		insert into dim_product (product_id, product_name, current_category)
		select s.product_id, s.product_name, s.category
		FROM stg_product s
		where not exists (
			SELECT 1 FROM dim_product d WHERE d.product_id = s.product_id
		);
	END;
$$

