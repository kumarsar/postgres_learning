create or replace procedure load_dim_product_scd3_2()
language plpgsql as 
$$
	declare bad_count int;
	Begin
		-- Guard: every staged category must exist in categories
		select count(*) into bad_count
		from stg_product s
		left join categories c on c.category_name = s.category
		WHERE c.category_name IS NULL;

		IF bad_count > 0 THEN
        	RAISE EXCEPTION '% staged rows have a category not in categories', bad_count;
    	END IF;
		
		-- 1) Changed: shift current -> previous, then overwrite current
		UPDATE dim_product d
    		SET previous_category   = d.current_category,   -- RHS sees the OLD value
        	current_category    = s.category,
        	category_changed_on = current_date
    	FROM stg_product s
    	WHERE d.product_id = s.product_id
      		AND d.current_category IS DISTINCT FROM s.category;
			  
		-- 2) New products (item_id comes from the identity)
	    INSERT INTO dim_product (product_id, product_name, current_category)
    	SELECT s.product_id, s.product_name, s.category
    	FROM stg_product s
    	WHERE NOT EXISTS (SELECT 1 FROM dim_product d WHERE d.product_id = s.product_id);	
	end;
$$

CALL load_dim_product_scd3_2();

