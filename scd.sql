-- SCD3 on dim_product for the category split -- 

/*
Assumptions :

product_id is the business key (the product's identity in the source system).
item_id is the surrogate PK of the dimension row, so it needs to auto-generate.
categories holds the new structure, and current_category / previous_category store category_name values from it.
The load matches on product_id, never on item_id, so surrogate keys never get reassigned.

*/
DROP TABLE IF EXISTS dim_product, stg_product, categories;

-- New category structure (exactly as product specified)

CREATE TABLE categories (
    item_id       int PRIMARY KEY,
    category_id   int,
    category_name varchar(100) NOT NULL UNIQUE   -- unique so names can be validated/joined
);

